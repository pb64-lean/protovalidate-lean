// Naming helpers

func protoStem(path string) string {
	base := path
	if i := strings.LastIndexByte(base, '/'); i >= 0 {
		base = base[i+1:]
	}
	return strings.TrimSuffix(base, ".proto")
}

// qualifyParts renders a dotted proto name as a Lean identifier path,
// quoting components that collide with Lean keywords.
func qualifyParts(name string) string {
	parts := strings.Split(name, ".")
	out := make([]string, 0, len(parts))
	for _, p := range parts {
		if p != "" {
			out = append(out, celtolean.LeanIdent(p))
		}
	}
	return strings.Join(out, ".")
}

// baseQualified is the absolute Lean name of a grpc-lean generated type.
func baseQualified(name protoreflect.FullName) string {
	return "_root_." + qualifyParts(string(name))
}

// validNamespace is the namespace holding validated variants for a package.
func validNamespace(pkg protoreflect.FullName) string {
	if pkg == "" {
		return "Valid"
	}
	return qualifyParts(string(pkg)) + ".Valid"
}

// validQualified is the absolute Lean name of a message's validated variant.
func validQualified(m *protogen.Message) string {
	pkg := m.Desc.ParentFile().Package()
	local := strings.TrimPrefix(string(m.Desc.FullName()), string(pkg)+".")
	if pkg == "" {
		local = string(m.Desc.FullName())
	}
	return "_root_." + validNamespace(pkg) + "." + qualifyParts(local)
}

// localName is a message's declaration name inside its package's Valid
// namespace (nested messages keep their dotted path).
func localName(m *protogen.Message) string {
	pkg := m.Desc.ParentFile().Package()
	local := string(m.Desc.FullName())
	if pkg != "" {
		local = strings.TrimPrefix(local, string(pkg)+".")
	}
	return qualifyParts(local)
}

var scalarLean = map[protoreflect.Kind]string{
	protoreflect.BoolKind:     "Bool",
	protoreflect.Int32Kind:    "Int32",
	protoreflect.Sint32Kind:   "Int32",
	protoreflect.Sfixed32Kind: "Int32",
	protoreflect.Int64Kind:    "Int64",
	protoreflect.Sint64Kind:   "Int64",
	protoreflect.Sfixed64Kind: "Int64",
	protoreflect.Uint32Kind:   "UInt32",
	protoreflect.Fixed32Kind:  "UInt32",
	protoreflect.Uint64Kind:   "UInt64",
	protoreflect.Fixed64Kind:  "UInt64",
	protoreflect.FloatKind:    "Float32",
	protoreflect.DoubleKind:   "Float",
	protoreflect.StringKind:   "String",
	protoreflect.BytesKind:    "ByteArray",
}

func scalarText(kind protoreflect.Kind, enum protoreflect.EnumDescriptor, msg protoreflect.MessageDescriptor) (string, error) {
	if s, ok := scalarLean[kind]; ok {
		return s, nil
	}
	switch kind {
	case protoreflect.EnumKind:
		return baseQualified(enum.FullName()), nil
	case protoreflect.MessageKind:
		return baseQualified(msg.FullName()), nil
	}
	return "", fmt.Errorf("unsupported field kind %v", kind)
}

func uniqueName(base string, taken map[string]bool) string {
	name := base
	for i := 1; taken[name]; i++ {
		name = fmt.Sprintf("%s_%d", base, i)
	}
	taken[name] = true
	return name
}

// sanitizeRuleID turns a CEL rule id into a Lean-friendly identifier stem.
func sanitizeRuleID(id string, ordinal int) string {
	var b strings.Builder
	for _, r := range id {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '_':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	s := b.String()
	if s == "" {
		return fmt.Sprintf("rule_%d", ordinal)
	}
	if s[0] >= '0' && s[0] <= '9' {
		s = "rule_" + s
	}
	return s
}

func docText(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.ReplaceAll(s, "-/", "- /")
}
